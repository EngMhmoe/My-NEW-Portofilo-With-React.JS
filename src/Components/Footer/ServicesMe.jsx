// ============================================================
// React Hooks
// ============================================================
import { useContext } from "react";

// ============================================================
// Motion
// ============================================================
import { motion } from "motion/react";

// ============================================================
// Context Provider
// ============================================================
import Mohamed from "../../context/ContextDarkMode";

// ============================================================
// Translation
// ============================================================
import { useTranslation } from "react-i18next";

// ============================================================
// Data
// ============================================================
import { services } from "../../Data/Footer Component/servicesMe";

// ============================================================
// Component
// ============================================================
export default function ServicesMe() {
  // ============================================================
  // Dark Mode
  // ============================================================
  const { darkMode } = useContext(Mohamed);

  // ============================================================
  // Translation
  // ============================================================
  const { t } = useTranslation();

  // ============================================================
  // Styles
  // ============================================================
  const titleStyle = `
    mb-4
    flex
    gap-3
    items-center
    justify-center
    font-bold
    uppercase
    md:justify-start
    text-2xl
    ${darkMode ? "text-red-800" : "text-[#ef5979]"}
  `;

  const itemStyle = "mb-2";

  // ============================================================
  // Render
  // ============================================================
  return (
    <motion.div
      // ========================================================
      // Refresh Animation Only
      // ========================================================
      initial={{
        opacity: 0,
        x: 45,
      }}
      animate={{
        opacity: 1,
        x: 0,
      }}
      transition={{
        duration: 1.3,
        delay: 0.2,
        ease: "easeOut",
      }}
      className="capitalize"
    >
      {/* ======================================================
          Section Title
      ====================================================== */}
      <h3 className={titleStyle}>{t("Services".toLowerCase())}</h3>

      {/* /////////////////////////////////////////////////////////////////////////// */}
      {/* /////////////////////////////////////////////////////////////////////////// */}

      {/* ======================================================
          Services List
      ====================================================== */}
      {services.map((service, index) => (
        <motion.p
          key={service}
          className={index === services.length - 1 ? "" : itemStyle}
          // ====================================================
          // Refresh Animation Only
          // ====================================================
          initial={{
            opacity: 0,
            y: 15,
          }}
          animate={{
            opacity: 1,
            y: 0,
          }}
          transition={{
            duration: 0.7,
            delay: 0.45 + index * 0.12,
            ease: "easeOut",
          }}
        >
          <a>{t(service.toLowerCase())}</a>
        </motion.p>
      ))}
    </motion.div>
  );
}
