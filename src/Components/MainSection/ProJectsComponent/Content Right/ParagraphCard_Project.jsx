//============================================================
// React Hooks
//============================================================
import { useContext } from "react";

//============================================================
// Translation
//============================================================
import { useTranslation } from "react-i18next";

//============================================================
// Context Provider
//============================================================
import Mohamed from "../../../../context/ContextDarkMode";

//============================================================
// Component
//============================================================
export default function ParagraphCard_Project({ description }) {
  //==========================================================
  // Dark Mode
  //==========================================================
  const { darkMode } = useContext(Mohamed);

  //==========================================================
  // Translation
  //==========================================================
  const { t } = useTranslation();

  //==========================================================
  // Styles
  //==========================================================

  // Description
  const descriptionStyle = `
    text-[15px]
    leading-relaxed
    mb-5
    lg:line-clamp-3
    md:line-clamp-4
    line-clamp-3
    group-hover:line-clamp-none
    ${darkMode ? "text-black/75" : "text-white/75"}
  `;

  //==========================================================
  // Render
  //==========================================================
  return <p className={descriptionStyle}>{t(description)}</p>;
}
