//============================================================
// React
//============================================================
import { useContext } from "react";

//============================================================
// Translation
//============================================================
import { useTranslation } from "react-i18next";

//============================================================
// Context
//============================================================
import Mohamed from "../../../context/ContextDarkMode";

//============================================================
// Component
//============================================================
export default function DescriptionCard({ Service }) {
  //==========================================================
  // Dark Mode
  //==========================================================
  const { darkMode } = useContext(Mohamed);

  //==========================================================
  // Translation
  //==========================================================
  const { t } = useTranslation();

  //==========================================================
  // Styles
  //==========================================================

  // Description Style
  const descriptionStyle = `
    capitalize
    text-muted-foreground
    mb-6
    ${darkMode ? "text-black/60" : "text-blue-100/60"}
  `;

  //==========================================================
  // Render
  //==========================================================

  return (
    <p className={descriptionStyle}>{t(Service.description.toLowerCase())}.</p>
  );
}
