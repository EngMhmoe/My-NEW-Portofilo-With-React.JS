//============================================================
// React
//============================================================
import { useContext } from "react";

//============================================================
// Translation
//============================================================
import { useTranslation } from "react-i18next";

//============================================================
// Context
//============================================================
import Mohamed from "../../../context/ContextDarkMode";

//============================================================
// Component
//============================================================
export default function TitleCard({ Service }) {
  //==========================================================
  // Dark Mode
  //==========================================================
  const { darkMode } = useContext(Mohamed);

  //==========================================================
  // Translation
  //==========================================================
  const { t } = useTranslation();

  //==========================================================
  // Styles
  //==========================================================

  // Title Style
  const titleStyle = `
    xl:text-2xl
    md:text-xl
    sm:text-lg
    text-2xl
    font-semibold
    mb-3
    capitalize
    transition-colors
    duration-900
    ${
      darkMode
        ? "text-black group-hover:text-red-800/95"
        : "text-blue-200 group-hover:text-[#d43c5d]"
    }
  `;

  //==========================================================
  // Render
  //==========================================================

  return <h1 className={titleStyle}>{t(Service.title.toLowerCase())}</h1>;
}
