//====================================================================================================
// Start Imports
//====================================================================================================

//============================================================
// React
//============================================================
import { useContext } from "react";

//============================================================
// Hooks
//============================================================
import useSelectedLang from "../../Hook/useSelectedLang";

//============================================================
// Context
//============================================================
import Mohamed from "../../context/ContextDarkMode";

//============================================================
// UI / Animations
//============================================================
import { motion } from "framer-motion";

//====================================================================================================
// End Imports
//====================================================================================================

//====================================================================================================
// Component
//====================================================================================================
export default function SelectedLang() {
  //==========================================================
  // Hooks
  //==========================================================
  const { changeLanguage, selectedLang, t } = useSelectedLang();

  //==========================================================
  // Dark Mode
  //==========================================================
  const { darkMode } = useContext(Mohamed);

  //==========================================================
  // Styles
  //==========================================================
  const selectedLangClasses = {
    select: `
      select
      h-9
      w-fit
      cursor-pointer
      capitalize
      border
      border-red-500
      font-bold
      shadow-lg
      shadow-red-600/35
      text-xl
      lg:text-lg
      ${darkMode ? "bg-red-800/90 text-white" : "bg-red-700/15 text-red-500"}
    `,

    option: "text-(--DarkMode-color) hover:text-(--primary-color)",
  };

  //==========================================================
  // Motion Variants
  //==========================================================

  // Initial Animation
  const selectedLangVariants = {
    hidden: {
      opacity: 0,
      y: -25,
      scale: 0.95,
    },

    visible: {
      opacity: 1,
      y: 0,
      scale: 1,

      transition: {
        type: "spring",
        stiffness: 80,
        damping: 18,
      },
    },
  };

  //==========================================================
  // Render
  //==========================================================
  return (
    <motion.select
      value={selectedLang}
      onChange={(e) => changeLanguage(e.target.value)}
      className={selectedLangClasses.select}
      variants={selectedLangVariants}
      initial="hidden"
      animate="visible"
      whileHover={{
        y: -2,
        scale: 1.02,

        transition: {
          type: "spring",
          stiffness: 400,
          damping: 15,
        },
      }}
      whileTap={{
        scale: 0.97,
      }}
    >
      {/*======================================================
          Disabled Language Option
      ======================================================*/}
      <option disabled>{t("english (us)".toLowerCase())}</option>

      {/* ////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////// */}

      {/*======================================================
          English Language Option
      ======================================================*/}
      <option value="en" className={selectedLangClasses.option}>
        {t("english".toLowerCase())}
      </option>

      {/* ////////////////////////////////////////////////////////////////////////////// */}
      {/* ////////////////////////////////////////////////////////////////////////////// */}

      {/*======================================================
          Arabic Language Option
      ======================================================*/}
      <option value="ar" className={selectedLangClasses.option}>
        {t("arabic".toLowerCase())}
      </option>
    </motion.select>
  );
}
