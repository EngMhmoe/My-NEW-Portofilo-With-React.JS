// ============================================================
// React Hooks
// ============================================================
import { useContext } from "react";

// ============================================================
// Context Provider
// ============================================================
import ContextProjectsData from "../context/ContextProjectsData";

// ============================================================
// Hook
// ============================================================
export default function useProjects() {
  // ============================================================
  // Context Provider
  // ============================================================
  const { Projects_Data, setCopyProjectsData } =
    useContext(ContextProjectsData);


  //////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////


  // ============================================================
  // All Projects
  // ============================================================
  function AllProjects() {
    setCopyProjectsData(Projects_Data);
  }


  //////////////////////////////////////////////////////////////////////////////////////////////////////
  //////////////////////////////////////////////////////////////////////////////////////////////////////


  // ============================================================
  // Function Filters Projects
  // ============================================================
  function FilterProjects(NameCardProject) {
    const filterProjects = Projects_Data.filter((project) => {
      return project.nameCard === NameCardProject;
    });

    setCopyProjectsData(filterProjects);
  }


  // ============================================================
  // Return
  // ============================================================
  return {
    AllProjects,
    FilterProjects,
  };
}